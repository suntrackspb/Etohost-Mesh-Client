#!/usr/bin/env python3
"""Regenerate the adapter for immutable settings metadata from the ARB catalog.

Do not use this adapter for messages, node names or other user-provided content.
UI widgets should use typed AppLocalizations accessors directly. Metadata keeps
its source labels so protobuf specifications remain independent of Flutter.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def main():
    catalog = json.loads((ROOT / 'lib/l10n/app_ru.arb').read_text())
    static, dynamic = [], []
    for key, value in catalog.items():
        if key.startswith('@'):
            continue
        meta = catalog.get('@' + key, {})
        source = meta.get('x-source')
        if source is None:
            continue
        args = list(meta.get('placeholders', {}))
        if not args:
            static.append(f'    {dart(source)} => l10n.{key},')
        else:
            parts = re.split(r'(\{arg\d+\})', source)
            if not re.search('[А-Яа-яЁё]', re.sub(r'\{arg\d+\}', '', source)):
                continue
            order = [p[1:-1] for p in parts if re.fullmatch(r'\{arg\d+\}', p)]
            pattern = '^' + ''.join(r'([\s\S]*?)' if re.fullmatch(r'\{arg\d+\}', p) else re.escape(p) for p in parts) + '$'
            params = ', '.join(
                f'localizeBuiltInText(l10n, m.group({order.index(arg)+1})!)'
                if arg in meta.get('x-localize-args', [])
                else f'm.group({order.index(arg)+1})!' for arg in args)
            dynamic.append(f'  (RegExp({dart(pattern)}), (AppLocalizations l10n, Match m) => l10n.{key}({params})),')
    result = '''// Generated by tool/gen_label_localizations.py. Do not edit.
import 'app_localizations.dart';

/// Localizes built-in metadata and errors, never user content.
String localizeBuiltInText(AppLocalizations l10n, String source) {
  if (l10n.localeName.startsWith('ru')) return source;
  final exact = switch (source) {
''' + '\n'.join(static) + '''
    _ => null,
  };
  if (exact != null) return exact;
  for (final (pattern, format) in _templates) {
    final match = pattern.firstMatch(source);
    if (match != null) return format(l10n, match);
  }
  final quantity = RegExp(r'^([0-9.,]+) ([^ ]+)$').firstMatch(source);
  if (quantity != null) {
    final unit = localizeBuiltInText(l10n, quantity.group(2)!);
    if (unit != quantity.group(2)) {
      return '${quantity.group(1)!.replaceAll(',', '.')} $unit';
    }
  }
  for (final separator in ['\\n\\n', '\\n', ' · ', ' › ', ', ', ': ']) {
    if (source.contains(separator)) {
      return source.split(separator).map((s) => localizeBuiltInText(l10n, s)).join(separator);
    }
  }
  return source;
}

final _templates = <(RegExp, String Function(AppLocalizations, Match))>[
''' + '\n'.join(dynamic) + '\n];\n'
    (ROOT / 'lib/l10n/built_in_text.dart').write_text(result)


if __name__ == '__main__':
    main()
